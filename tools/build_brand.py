#!/usr/bin/env python3
"""Original PNG artwork based on the user's S-snake/starry hills sketch."""
from pathlib import Path
from PIL import Image,ImageDraw
import math,random
root=Path(__file__).resolve().parents[1];out=root/'assets/brand';out.mkdir(exist_ok=True)
S=4
im=Image.new('RGBA',(256*S,256*S));d=ImageDraw.Draw(im)
def path(points,width,color):
 pts=[]
 for a,b,c,e in points:
  for j in range(65):
   t=j/64;q=1-t;pts.append((S*(q*q*q*a[0]+3*q*q*t*b[0]+3*q*t*t*c[0]+t*t*t*e[0]),S*(q*q*q*a[1]+3*q*q*t*b[1]+3*q*t*t*c[1]+t*t*t*e[1])))
 d.line(pts,fill=color,width=width*S,joint='curve')
 for x,y in (pts[0],pts[-1]):d.ellipse((x-width*S/2,y-width*S/2,x+width*S/2,y+width*S/2),fill=color)
path([((70,205),(211,226),(219,129),(126,128)),((126,128),(39,127),(60,48),(150,52))],38,'#376f56')
path([((70,197),(203,218),(211,121),(126,120)),((126,120),(47,119),(65,40),(154,44))],34,'#8bc96e')
d.rounded_rectangle((117*S,26*S,198*S,79*S),radius=19*S,fill='#8bc96e')
d.ellipse((171*S,38*S,181*S,48*S),fill='#173d3b')
d.line([(195*S,65*S),(217*S,65*S),(227*S,54*S)],fill='#ec7279',width=7*S)
d.line([(217*S,65*S),(231*S,67*S)],fill='#ec7279',width=6*S)
# pale belly accents, kept sparse for readability at 32px
for x,y in [(91,91),(79,162),(144,183)]:d.rounded_rectangle((x*S,y*S,(x+12)*S,(y+6)*S),radius=2*S,fill='#a9dc86')
im=im.resize((256,256),Image.Resampling.LANCZOS);im.save(out/'slopix-snake-256.png')
small=im.convert('RGBa').resize((28,28),Image.Resampling.LANCZOS).convert('RGBA');raw=small.tobytes()
(root/'src/brand.h').write_text('/* Generated by tools/build_brand.py */\nstatic const unsigned char slopix_logo[3136]={'+','.join(map(str,raw))+'};\n')
w,h=1280,800;im=Image.new('RGB',(w,h));pix=im.load()
for y in range(h):
 t=y/(h-1);c=tuple(round(a+(b-a)*t) for a,b in zip((15,31,51),(35,70,78)))
 for x in range(w):pix[x,y]=c
D=ImageDraw.Draw(im);random.seed(17)
for _ in range(95):
 x=random.randrange(20,w-20);y=random.randrange(50,510);r=random.choice([1,1,1,2]);D.ellipse((x-r,y-r,x+r,y+r),fill=random.choice(['#9fbcb9','#d5dfce','#698d98']))
D.ellipse((1000,115,1094,209),fill='#d9dfb4');D.ellipse((1020,99,1110,189),fill=(22,43,62))
for color,base,amp,phase in [('#244e54',520,78,.5),('#346c5b',610,75,2.1),('#478751',700,62,4.2)]:
 pts=[(x,base+int(amp*math.sin(x/300+phase)+20*math.cos(x/97))) for x in range(0,w+1,4)]+[(w,h),(0,h)];D.polygon(pts,fill=color)
im.save(out/'night-hills-1280x800.png',optimize=True);(out/'wallpaper.rgb').write_bytes(im.tobytes())
