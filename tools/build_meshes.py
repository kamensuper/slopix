#!/usr/bin/env python3
"""Original parametric meshes, generated offline as bounded fixed-point data.
The teapot is our own lathed design with swept handle/spout, not Utah data.
"""
from pathlib import Path
import math
Q=65536
out=['/* Generated by tools/build_meshes.py; original Slopix meshes. */','struct mesh_face {struct vec a,b,c,n;uint32_t color;};']
def mesh(name,faces):
 out.append('static const struct mesh_face '+name+'[]={')
 for a,b,c,color in faces:
  u=[b[i]-a[i] for i in range(3)];v=[c[i]-a[i] for i in range(3)]
  n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]];l=math.sqrt(sum(x*x for x in n))
  if l<1e-8:continue
  def vec(v):return '{'+','.join(str(round(x*Q)) for x in v)+'}'
  out.append('{'+','.join(vec(v) for v in [a,b,c,[x/l for x in n]])+',0x%06x},'%color)
 out.append('};')
def grid(fn,nu,nv,color):
 f=[]
 for i in range(nu):
  for j in range(nv):
   a,b,c,d=fn(i/nu,j/nv),fn((i+1)/nu,j/nv),fn((i+1)/nu,(j+1)/nv),fn(i/nu,(j+1)/nv)
   col=color(i,j) if callable(color) else color
   f.extend([(a,b,c,col),(a,c,d,col)])
 return f
pi=math.pi
mesh('torus_mesh',grid(lambda u,v:((.95+.35*math.cos(v*2*pi))*math.cos(u*2*pi),.35*math.sin(v*2*pi),(.95+.35*math.cos(v*2*pi))*math.sin(u*2*pi)),32,12,lambda i,j:0xe6a45e if i%4<2 else 0xd986b8))
f=[]
for i in range(64):
 a=i*2*pi/64;b=(i+1)*2*pi/64
 f.append(((0,0,0),(1.25*math.cos(a),1.25*math.sin(a),0),(1.25*math.cos(b),1.25*math.sin(b),0),[0x54d9df,0x6d9dff,0xb28aff,0x59d69c][i//16]))
mesh('circle_mesh',f)
f=[]
def lathe(profile,color):
 def fn(u,v):
  j=min(len(profile)-2,int(v*(len(profile)-1)));t=v*(len(profile)-1)-j
  y=profile[j][0]*(1-t)+profile[j+1][0]*t;r=profile[j][1]*(1-t)+profile[j+1][1]*t
  return (r*math.cos(u*2*pi),y,r*math.sin(u*2*pi))
 return grid(fn,24,len(profile)-1,color)
f+=lathe([(.65,.05),(.65,.55),(.5,.78),(.2,.9),(-.15,.88),(-.4,.68),(-.5,.5)],0x59c9bc)
f+=lathe([(-.5,.56),(-.58,.55),(-.67,.4),(-.72,.12),(-.82,.13),(-.9,.04)],0xf1c16c)
# Curved tapered spout: axis mostly right, bend upward
f+=grid(lambda u,v:(.62+v*.95, -.05-v*v*.65+(.24-v*.13)*math.cos(u*2*pi),(.24-v*.13)*math.sin(u*2*pi)),12,8,0x59c9bc)
# Open C handle behind left side of body
f+=grid(lambda u,v:(-.7-.62*math.cos((v-.5)*pi*1.2)+.10*math.cos(u*2*pi)*math.cos((v-.5)*pi*1.2),.02+.53*math.sin((v-.5)*pi*1.2)+.10*math.cos(u*2*pi)*math.sin((v-.5)*pi*1.2),.10*math.sin(u*2*pi)),8,20,0xf1c16c)
mesh('teapot_mesh',f)
Path(__file__).resolve().parents[1].joinpath('src/meshes.h').write_text('\n'.join(out)+'\n')
