#!/usr/bin/env python3
"""Original vector primitives -> 256 px PNG -> premultiplied Lanczos RGBA.
Existing application PNG masters are reused. No runtime SVG/HVIF decoder.
"""
from pathlib import Path
from PIL import Image, ImageDraw
from build_icons import resize_icon
ROOT=Path(__file__).resolve().parents[1]
SIZES=(16,24,32,48,64,96)
NAMES=('terminal','demo','doom','find','settings','files','document','image','disk','sound','system')
def original(name):
    im=Image.new('RGBA',(256,256));d=ImageDraw.Draw(im)
    edge='#294858';light='#fff5bc';gold='#dfac42'
    if name=='files':
        d.rounded_rectangle((20,51,233,222),radius=15,fill='#183b4c')
        d.rounded_rectangle((24,30,122,98),radius=12,fill=edge)
        d.rounded_rectangle((31,37,115,103),radius=8,fill=light)
        d.rounded_rectangle((25,65,229,217),radius=11,fill=gold)
        d.polygon([(30,91),(224,91),(208,211),(35,211)],fill='#edc85b')
        d.line([(34,94),(218,94)],fill=light,width=6)
        d.line([(40,201),(204,201)],fill='#c08a2c',width=3)
    elif name in ('document','image'):
        d.polygon([(52,19),(159,19),(208,69),(208,235),(52,235)],fill=edge)
        d.polygon([(59,26),(153,26),(201,74),(201,228),(59,228)],fill='#f4f4e6')
        d.polygon([(153,27),(153,76),(201,76)],fill='#80bdcf')
        if name=='image':
            d.rectangle((75,102,184,184),fill='#8ccbd9',outline=edge,width=3)
            d.ellipse((151,113,172,134),fill=light)
            d.polygon([(78,177),(110,130),(135,161),(152,144),(182,178)],fill='#468f8a')
        else:
            for y in (105,127,149,171):d.rounded_rectangle((77,y,180,y+7),radius=2,fill='#7896a3')
        d.rectangle((77,201,159,206),fill='#b5c4c6')
    elif name=='disk':
        d.rounded_rectangle((26,43,230,220),radius=15,fill=edge)
        d.rounded_rectangle((32,49,224,213),radius=10,fill='#a9c2ca')
        d.polygon([(39,51),(217,51),(199,169),(57,169)],fill='#dae7e7')
        d.rounded_rectangle((38,177,218,205),radius=4,fill='#446477')
