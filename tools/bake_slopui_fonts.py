#!/usr/bin/env python3
"""Bake the SlopUI font atlases into sdk/slopfont_data.h.

Reproducible: same font files + same Pillow FreeType => byte-identical output.
  python3 tools/bake_slopui_fonts.py --sans NotoSans[wght].ttf \
      --mono LiberationMono-Regular.ttf -o sdk/slopfont_data.h

Coverage: printable ASCII (U+0020..U+007E) only. No kerning, no Unicode.
Storage: 4-bit alpha, two pixels per byte, rows padded to whole bytes.
Advances are stored in 1/16 px so proportional text does not drift.
"""
import argparse, hashlib, os
from PIL import Image, ImageDraw, ImageFont

FACES = [  # (C identifier, role, size in px)
    ("sf_ui12", "sans", 12), ("sf_ui14", "sans", 14), ("sf_ui18", "sans", 18),
    ("sf_ui14b", "sans-bold", 14), ("sf_ui18b", "sans-bold", 18),
    ("sf_mono13", "mono", 13), ("sf_mono15", "mono", 15),
]
FIRST, LAST = 32, 126

def load(path, size, bold):
    f = ImageFont.truetype(path, size)
    try:  # variable Noto Sans: pick named instance explicitly for reproducibility
        f.set_variation_by_axes([600 if bold else 400])
    except Exception:
        pass
    return f

def bake(font):
    asc, desc = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv16 = int(round(font.getlength(ch) * 16))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = img.load()
            for y in range(h):
                for x in range(0, w, 2):
                    a = (px[x, y] + 8) // 17
                    b = (px[x + 1, y] + 8) // 17 if x + 1 < w else 0
                    data.append((a << 4) | b)
        glyphs.append((off, w, h, x0, y0, adv16))
    return asc, desc, glyphs, bytes(data)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sans", required=True)
    ap.add_argument("--mono", required=True)
    ap.add_argument("-o", "--out", default="sdk/slopfont_data.h")
    a = ap.parse_args()
    paths = {"sans": a.sans, "sans-bold": a.sans, "mono": a.mono}
    out = ["/* GENERATED by tools/bake_slopui_fonts.py — do not edit. */",
           "/* Sources (SIL Open Font License 1.1, see assets/SLOPUI-FONTS-LICENSE.md):"]
    for role in ("sans", "mono"):
        h = hashlib.sha256(open(paths[role], "rb").read()).hexdigest()
        out.append(" *   %s: %s sha256=%s" % (role, os.path.basename(paths[role]), h))
    out += [" * Coverage: ASCII 0x20-0x7E. 4-bit alpha, 2 px/byte. */",
            "#ifndef SLOPFONT_DATA_H", "#define SLOPFONT_DATA_H", '#include "slopfont_types.h"']
    total = 0
    for name, role, size in FACES:
        asc, desc, glyphs, data = bake(load(paths[role], size, role == "sans-bold"))
        total += len(data)
        out.append("static const uint8_t %s_bits[%d] = {" % (name, max(1, len(data))))
        for i in range(0, len(data), 32):
            out.append(" " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        if not data: out.append(" 0")
        out.append("};")
        out.append("static const sf_glyph %s_glyphs[95] = {" % name)
        for g in glyphs:
            out.append(" {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append("static const sf_font %s = {%s_glyphs, %s_bits, %d, %d, %d, %d};" %
                   (name, name, name, size, asc, desc, asc + desc + max(2, size // 5)))
    out.append("#endif")
    open(a.out, "w").write("\n".join(out) + "\n")
    print("wrote %s, %d glyph bytes" % (a.out, total))

if __name__ == "__main__":
    main()
